// * ask marks (float) and age(int) from user
#include <stdio.h>

int main()
{
    float marks;
    int age;

    printf("Enter marks : ");
    scanf("%f", &marks);

    printf("Enter age : ");
    scanf("%d", &age);

    printf("Age : %d\n", age);
    printf("Marks : %f\n", marks);
    return 0;
}
